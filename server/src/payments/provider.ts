/**
 * Порт платёжного провайдера (E8-01).
 *
 * Юридическое лицо и провайдер основателем не названы, а маршрут оплаты ждать
 * их не обязан: он не зависит от того, кто именно проводит платёж. Поэтому
 * оплата написана против этого интерфейса — тем же приёмом, что и база
 * (`server/src/db/driver.ts`). В репозитории живёт поддельная реализация для
 * тестов и сквозных прогонов; реальный адаптер добавляется одним модулем и
 * одной строкой в реестре, когда провайдер станет известен.
 *
 * Что остаётся дописать под реального провайдера — в `docs/14-state.md`,
 * область «Сервер, оплата, инфраструктура».
 *
 * Границы порта:
 *
 * 1. Провайдер не знает ни про профиль, ни про срез как продукт: он получает
 *    заказ, сумму и адрес возврата. Продуктовые правила остаются на сервере.
 * 2. Провайдер не ходит в базу. Уведомление он только разбирает и проверяет;
 *    что с ним делать — решает сервер.
 * 3. Провайдер не бросает исключений на «платёж не прошёл»: это нормальный
 *    исход, он приходит уведомлением.
 */

/** Режим провайдера. `test` означает, что настоящих денег нет ни при каких настройках. */
export type PaymentMode = "test" | "live";

export interface PaymentRequest {
  orderId: string;
  /** Сумма в рублях целым числом: копеек в маршруте нет. */
  amount: number;
  currency: string;
  /** Что покупается — идентификатор среза. Продуктовый текст провайдеру не нужен. */
  slice: string;
  /** Куда вернуть человека после оплаты: его же страница. */
  returnUrl: string;
}

export interface PaymentHandle {
  /** Идентификатор платежа у провайдера. Хранится в заказе. */
  reference: string;
  /** Адрес, куда вести человека. */
  url: string;
}

/**
 * Что провайдер сообщает уведомлением. Три исхода — больше маршруту не нужно:
 * успех, отказ и возврат.
 */
export type WebhookKind = "payment.succeeded" | "payment.failed" | "refund.succeeded";

export interface WebhookEvent {
  /**
   * Идентификатор уведомления у провайдера. Ключ защиты от повторной доставки:
   * провайдеры повторяют уведомление, пока не получат подтверждение.
   */
  eventId: string;
  kind: WebhookKind;
  orderId: string;
  reference: string;
  amount: number;
  currency: string;
}

export interface RefundRequest {
  reference: string;
  amount: number;
  currency: string;
}

export interface RefundHandle {
  reference: string;
}

/** Заголовки уведомления в том виде, в каком их отдаёт `node:http`. */
export type WebhookHeaders = Record<string, string | string[] | undefined>;

export interface PaymentProvider {
  readonly name: string;
  readonly mode: PaymentMode;
  /** Заводит платёж и отдаёт адрес, куда вести человека. */
  createPayment(request: PaymentRequest): PaymentHandle;
  /**
   * Адрес уже заведённого платежа. Нужен, когда человек нажал «купить» снова,
   * а заказ ещё не оплачен: второго платежа нет, ведём на тот же.
   */
  checkoutUrl(reference: string, returnUrl: string): string;
  /**
   * Разбирает уведомление и проверяет подпись.
   * `null` — подпись не сошлась или тело не разобрано. Сервер отвечает отказом
   * и ничего не меняет: разбирать неподписанное уведомление опаснее, чем
   * потерять его — провайдер доставит повторно.
   */
  parseWebhook(raw: string, headers: WebhookHeaders): WebhookEvent | null;
  /** Возврат средств. Успех подтверждается отдельным уведомлением. */
  refund(request: RefundRequest): RefundHandle;
}
