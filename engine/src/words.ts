/**
 * Подсчёт слов в русском тексте.
 *
 * Здесь нет продуктовых правил: только то, как из строки получаются слова.
 * Дефис внутри слова не разрывает («когда-нибудь» — одно слово).
 */

/** Слова текста: буквы и цифры, дефис внутри слова не разрывает. */
export const words = (text: string): string[] => text.match(/[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*/gu) ?? [];

/** Число слов. Объём lookup-блоков и эталонов считается отсюда, а не пробелами. */
export const wordCount = (text: string): number => words(text).length;
