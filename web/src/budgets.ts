/**
 * Бюджеты производительности (E10-09).
 *
 * Числа — из `docs/12-target-state.md`, раздел 5.9. Превышение — отказ, а не
 * предупреждение: `assertBudget` бросает, и `npm run lint:budget` роняет сборку.
 *
 * LCP и CLS из того же раздела здесь не измеряются: для них нужен браузер
 * и сеть, а внешних сервисов в конвейере нет. Вместо них — то, что считается
 * по собранному дереву: вес, число модулей (каждый — отдельный запрос на 4G)
 * и отсутствие веб-шрифта (перескок текста).
 */

/** Скрипты первой загрузки после gzip, КБ. */
export const SCRIPT_BUDGET_KB = 150;
/** Стили первой загрузки после gzip, КБ. */
export const STYLE_BUDGET_KB = 30;
/**
 * Модулей в графе первой загрузки. Без сборщика каждый файл — запрос;
 * запас, чтобы E7 не раздул граф молча.
 */
export const MODULE_COUNT_BUDGET = 48;
/** Таблиц стилей продукта на странице. Вторая — второй запрос и риск FOUC. */
export const STYLESHEET_BUDGET = 1;

/**
 * Сравнивает факт с бюджетом. Превышение бросает: вызывающий не может
 * проглотить это как предупреждение.
 */
export function assertBudget(name: string, actual: number, budget: number): void {
  if (actual > budget) {
    throw new Error(`${name}: ${actual} при бюджете ${budget}`);
  }
}
