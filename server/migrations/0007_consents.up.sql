-- E9-01 · Согласие на обработку данных.
--
-- Отдельная таблица, а не колонка в профиле: факт согласия — самостоятельное
-- юридическое событие, и его нужно хранить вместе с версией документа.
-- Версия — отпечаток полного текста согласия, а не номер из markdown: его
-- некому поднимать, а правка документа сама меняет то, что запишется в базу.
--
-- Один профиль — одна актуальная отметка. Повторная запись той же строки
-- обновляет версию и время: отдельного журнала редакций в этой задаче нет.

CREATE TABLE consents (
  profile_id    TEXT NOT NULL PRIMARY KEY,
  version       TEXT NOT NULL,
  consented_at  TEXT NOT NULL,
  FOREIGN KEY (profile_id) REFERENCES profiles (profile_id) ON DELETE CASCADE,
  CHECK (length(version) = 64)
);
