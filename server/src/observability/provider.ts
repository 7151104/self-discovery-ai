/**
 * Порт приёмника ошибок (E10-06).
 *
 * Внешнего аккаунта трекера нет (как и платёжного провайдера, и модели),
 * а ошибки собирать уже нужно: иначе падение на рабочей машине видно только
 * в журнале процесса, и без версии сборки. Поэтому сервер смотрит на этот
 * интерфейс, а в репозитории живёт поддельная реализация. Настоящий адаптер —
 * один модуль и одна строка в реестре, когда основатель назовёт сервис.
 *
 * Границы порта:
 *
 * 1. Приёмник не знает ни про профиль, ни про ответы: на вход уже очищенный
 *    отчёт. Чистка — на стороне сервера, тем же фильтром, что журнал (E9-04).
 * 2. Приёмник не ходит в базу и не отвечает клиенту. Он только принимает.
 * 3. Версия сборки приходит с отчётом: одно место на выпуск (`SDAI_BUILD_*`),
 *    а не отдельное поле, которое адаптер достаёт сам.
 */

/** Откуда пришла ошибка. Клиентская едет через эндпоинт, серверная — из процесса. */
export type ErrorSource = "server" | "client";

/**
 * Что уходит в приёмник. Полей про человека здесь нет даже по типу:
 * ни имени, ни даты рождения, ни текста ответа. `errorName` — класс ошибки
 * (`TypeError`), не имя человека: поле `name` фильтр журнала скрывает всегда.
 */
export interface ErrorReport {
  source: ErrorSource;
  /** Класс ошибки: `TypeError`, `Error`. Машинный код. */
  errorName: string;
  /** Сообщение после чистки. Человеческий текст сюда не попадает. */
  message: string;
  /** Версия сборки: то же поле, что в `GET /api/health`. */
  version: string;
  /** Коммит сборки. */
  commit: string;
  /** Время отчёта в ISO-8601. */
  occurredAt: string;
  /**
   * Путь запроса без строки параметров. Только если выглядит машинно:
   * `/api/health`, `/api/p/...`. Иначе поля нет.
   */
  route?: string;
}

export interface ErrorTracker {
  /** Устойчивый идентификатор реализации: `fake`, и дальше имя настоящего. */
  readonly name: string;
  capture(report: ErrorReport): void;
}
