export const GOOD_STORYLINE = {
  value: "берёт дело целиком и встаёт перед показом",
  code: "solo_then_stop_before_show",
  confidence: "medium" as const,
};

/** Машинный конверт в том виде, в котором его отдаёт модель. */
export function envelope(
  overrides: {
    text?: string;
    statements?: Statement[];
    storyline?: { value?: string; code?: string; confidence?: string } | null;
    extra?: Record<string, unknown>;
  } = {},
): string {
  const storyline =
    overrides.storyline === null
      ? undefined
      : {
          значение: overrides.storyline?.value ?? GOOD_STORYLINE.value,
          код: overrides.storyline?.code ?? GOOD_STORYLINE.code,
          уверенность: overrides.storyline?.confidence ?? GOOD_STORYLINE.confidence,
        };

  return JSON.stringify({
    текст: overrides.text ?? GOOD_TEXT,
    утверждения: (overrides.statements ?? GOOD_STATEMENTS).map((item) => ({
      фраза: item.phrase,
      вид: item.kind,
      координата: item.coordinate,
    })),
    ...(storyline ? { сюжет: storyline } : {}),
    ...(overrides.extra ?? {}),
  });
}
